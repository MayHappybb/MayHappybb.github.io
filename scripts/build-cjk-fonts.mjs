// Chinese fonts for the few Chinese words on the site, cut down to exactly the characters used.
//   LXGW WenKai (OFL 1.1, drawn from Klee One) for body text, so English and Chinese share one hand.
//   ZCOOL KuaiLe (OFL 1.1), a round felt-pen hand, beside Gaegu in headings.
// Usage: node scripts/build-cjk-fonts.mjs          check that every Chinese character in src/ is covered
//        node scripts/build-cjk-fonts.mjs --write  re-subset (downloads the full fonts once into fonts-src/)
// The output (public/fonts/cjk/*.woff2, src/styles/cjk-fonts.css) is committed; fonts-src/ is not.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const SRC = 'fonts-src';
const OUT = 'public/fonts/cjk';
const FONTS = [
  { out: 'wenkai-400.woff2', family: 'LXGW WenKai', weight: 400, file: 'LXGWWenKai-Regular.ttf',
    url: 'https://github.com/lxgw/LxgwWenKai/releases/download/v1.530/LXGWWenKai-Regular.ttf', size: 25928940 },
  // WenKai has no Bold; Medium is its heaviest weight and is used for bold text
  { out: 'wenkai-700.woff2', family: 'LXGW WenKai', weight: 700, file: 'LXGWWenKai-Medium.ttf',
    url: 'https://github.com/lxgw/LxgwWenKai/releases/download/v1.530/LXGWWenKai-Medium.ttf', size: 25800076 },
  { out: 'kuaile-400.woff2', family: 'ZCOOL KuaiLe', weight: 400, file: 'ZCOOLKuaiLe-Regular.ttf',
    url: 'https://raw.githubusercontent.com/google/fonts/main/ofl/zcoolkuaile/ZCOOLKuaiLe-Regular.ttf', size: 1514968 },
];
// sizes from the GitHub release / repository metadata; SHA-256 pinned on the first good download
const HASHES = 'scripts/cjk-fonts.sha256.json';

// Chinese characters and CJK punctuation used anywhere in src/ (the kit is built from src/ too)
const CJK = /[　-〿㐀-鿿＀-￯]/gu;
const chars = new Set();
const walk = (d) => readdirSync(d).forEach((f) => {
  const p = join(d, f);
  if (statSync(p).isDirectory()) walk(p);
  else if (/\.(md|astro|ts|js)$/.test(f) && !f.startsWith('cjk-fonts')) for (const c of readFileSync(p, 'utf8').match(CJK) ?? []) chars.add(c);
});
walk('src');
// the clock gallery's blurbs load these fonts through the kit too
const GALLERY = join(process.env.HOME ?? '', 'coding/clock-skills/gallery/manifest.json');
const EXTRA = 'scripts/cjk-extra-chars.txt';
if (existsSync(GALLERY) && process.argv.includes('--write')) writeFileSync(EXTRA, [...new Set(readFileSync(GALLERY, 'utf8').match(CJK) ?? [])].sort().join('') + '\n');
if (existsSync(EXTRA)) for (const c of readFileSync(EXTRA, 'utf8').match(CJK) ?? []) chars.add(c);
const text = [...chars].sort().join('');
const stamp = createHash('sha256').update(text).digest('hex').slice(0, 12);
const CSS = 'src/styles/cjk-fonts.css';

if (!process.argv.includes('--write')) {
  const css = existsSync(CSS) ? readFileSync(CSS, 'utf8') : '';
  if (!css.includes(`chars:${stamp}`)) {
    console.error(`CJK fonts are out of date (Chinese text in src/ changed). Run: node scripts/build-cjk-fonts.mjs --write`);
    process.exit(1);
  }
  console.log(`CJK fonts cover all ${chars.size} characters`);
  process.exit(0);
}

mkdirSync(SRC, { recursive: true }); mkdirSync(OUT, { recursive: true });
const pinned = existsSync(HASHES) ? JSON.parse(readFileSync(HASHES, 'utf8')) : {};
const faces = [];
for (const f of FONTS) {
  const path = join(SRC, f.file);
  if (!existsSync(path)) {
    console.log(`downloading ${f.url}`);
    const res = await fetch(f.url); if (!res.ok) throw new Error(`${f.url}: HTTP ${res.status}`);
    writeFileSync(path, Buffer.from(await res.arrayBuffer()));
  }
  const buf = readFileSync(path);
  if (buf.length !== f.size) throw new Error(`${f.file}: ${buf.length} bytes, expected ${f.size} (an interrupted download? delete it and run again)`);
  const sha = createHash('sha256').update(buf).digest('hex');
  const want = pinned[f.file];
  if (want && want !== sha) throw new Error(`${f.file}: checksum ${sha} does not match the pinned ${want}`);
  pinned[f.file] = sha;
  const out = await subsetFont(buf, text, { targetFormat: 'woff2' });
  writeFileSync(join(OUT, f.out), out);
  faces.push(`@font-face { font-family:'${f.family}'; font-style:normal; font-weight:${f.weight}; font-display:swap; src:url(/fonts/cjk/${f.out}) format('woff2'); unicode-range:U+3000-303F, U+3400-9FFF, U+FF00-FFEF; }`);
  console.log(`${f.out}: ${(out.length / 1024).toFixed(1)} KB`);
}
writeFileSync(HASHES, JSON.stringify(pinned, null, 2) + '\n');
// OFL 1.1: the licence travels with the fonts
for (const l of ['OFL-LXGWWenKai.txt', 'OFL-ZCOOLKuaiLe.txt']) if (existsSync(join(SRC, l))) writeFileSync(join(OUT, l), readFileSync(join(SRC, l)));
writeFileSync(CSS, `/* Generated by scripts/build-cjk-fonts.mjs --write (chars:${stamp}, ${chars.size} characters). Do not edit. */\n${faces.join('\n')}\n`);
console.log(`CJK fonts: ${chars.size} characters`);
